import assert from 'node:assert/strict';
import {roofProfile,roofShapeDescription} from '../src/roofGeometry.ts';
const rectangle=[{x:0,z:0},{x:20,z:0},{x:20,z:10},{x:0,z:10}];
const gabled=roofProfile({shape:'gabled',sourceId:1,score:.99,height:3},25,rectangle);
assert.ok(gabled);
assert.equal(gabled.rise,3);
assert.equal(gabled.eave,22);
assert.equal(gabled.estimated,false);
assert.ok(gabled.heightAt({x:10,z:5})>gabled.heightAt({x:10,z:0}));
assert.ok(gabled.heightAt({x:10,z:5})<=25);
const hip=roofProfile({shape:'hipped',sourceId:1,score:.99},20,rectangle);
assert.ok(hip);
assert.equal(hip.estimated,true);
assert.ok(hip.heightAt({x:10,z:5})>hip.heightAt({x:0,z:0}));
const flat=roofProfile({shape:'flat',sourceId:1,score:.99},25,rectangle);
assert.equal(flat?.rise,0);
assert.equal(flat?.heightAt({x:12,z:5}),25);
assert.equal(roofShapeDescription('mansard'),'toit mansardé');
assert.equal(roofProfile(undefined,24,rectangle),null);
console.log('Formes OSM : volumes préservés, altitudes limitées, inclinaison vérifiée.');
